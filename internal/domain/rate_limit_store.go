package domain

import (
	"context"
	"time"
)

// RateLimitStore — порт для хранения счётчиков ограничения частоты запросов
// (Clean Architecture: порты объявляются во внутреннем круге, в домене).
// Инфраструктурная реализация — internal/infrastructure/persistence.RateLimitRepository.
// Транспортный слой (middleware) зависит только от этого интерфейса и не
// содержит прямых SQL-запросов.
//
// Методы:
//   - Increment — атомарно увеличивает счётчик для ключа в текущем окне
//     фиксированной длительности window и возвращает результат с новым
//     значением счётчика и временем окончания окна. Окна привязаны к
//     «эпохе» (Unix epoch), поэтому все экземпляры сервиса используют
//     одинаковые границы окон без синхронизации.
//   - Reset — сбрасывает счётчик ключа (удаляет запись окна). Используется
//     политикой login_failed: успешный вход обнуляет счётчик неудачных
//     попыток, защищённого от account-lockout DoS.
//   - Cleanup — удаляет записи, чьё окно заведомо истекло (window_start +
//     maxWindow <= now()), чтобы таблица не росла бесконечно за счёт
//     одноразовых или устаревших ключей. Вызывается фоновым воркером.

// RateLimitResult — результат атомарного увеличения счётчика лимита.
type RateLimitResult struct {
	// Count — новое значение счётчика в текущем окне.
	Count int
	// ResetAt — момент окончания текущего окна фиксированной длительности.
	// По нему middleware вычисляет Retry-After = оставшееся до сброса время,
	// а не всю длину окна (требование HTTP 429).
	ResetAt time.Time
}

type RateLimitStore interface {
	// Increment увеличивает счетчик для ключа и возвращает новое значение
	// счётчика вместе с границей сброса текущего окна.
	Increment(ctx context.Context, key string, window time.Duration) (RateLimitResult, error)

	// Reset удаляет запись счётчика для ключа: следующее обращение откроет
	// новое окно со значения 0/1. Вызов для несуществующего ключа — no-op.
	Reset(ctx context.Context, key string) error

	// Cleanup удаляет устаревшие записи хранилища лимитов запросов.
	// maxWindow — максимально возможная длительность окна в системе
	// (например, 1 час для регистрации). Записи, чьё окно завершилось
	// более maxWindow назад, гарантированно не влияют на новые запросы
	// и могут быть безопасно удалены.
	Cleanup(ctx context.Context, maxWindow time.Duration) error
}
